-- ==========================================
-- 1. TIPE ENUM (Pilihan Tetap)
-- ==========================================

-- Role Tunggal untuk Internal (Kasir + Dapur + Admin jadi 1)
CREATE TYPE user_role AS ENUM ('pegawai');

-- Tipe Metode Pembayaran
CREATE TYPE payment_type AS ENUM ('qris', 'cash');

-- Status Pembayaran
CREATE TYPE payment_status AS ENUM ('pending', 'lunas', 'batal');

-- Status Pesanan Dimsum
CREATE TYPE order_status AS ENUM ('menunggu', 'disiapkan', 'selesai');


-- ==========================================
-- 2. TABEL-TABEL UTAMA
-- ==========================================

-- Tabel Profile Pegawai Single-Worker
CREATE TABLE profiles (
                          id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
                          username VARCHAR(50) NOT NULL UNIQUE,
                          role user_role DEFAULT 'pegawai',
                          created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel Menu Dimsum
CREATE TABLE menus (
                       id_menu BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nama_dimsum VARCHAR(100) NOT NULL,
                       harga NUMERIC(10, 2) NOT NULL CHECK (harga >= 0),
                       stok INT NOT NULL DEFAULT 0 CHECK (stok >= 0),
                       foto_url TEXT,
                       created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel Transaksi Utama (Orders)
CREATE TABLE orders (
                        id_order BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nomor_antrean INT NOT NULL,
                        nama_pembeli VARCHAR(50) NOT NULL,
                        tipe_pembayaran payment_type NOT NULL,
                        status_pembayaran payment_status DEFAULT 'pending',
                        status_pesanan order_status DEFAULT 'menunggu',
                        total_harga NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_harga >= 0),
                        created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel Detail Pesanan (OrderItem)
CREATE TABLE order_items (
                             id_detail BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_order BIGINT NOT NULL REFERENCES orders(id_order) ON DELETE CASCADE,
                             id_menu BIGINT NOT NULL REFERENCES menus(id_menu) ON DELETE RESTRICT,
                             jumlah INT NOT NULL CHECK (jumlah > 0),
                             subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0)
);


-- ==========================================
-- 3. LOGIKA OTOMATISASI (TRIGGERS & FUNCTIONS)
-- ==========================================

-- A. Fungsi Generate Nomor Antrean Berurutan yang Reset Otomatis Setiap Hari (WIB)
CREATE OR REPLACE FUNCTION generate_daily_queue_number()
RETURNS TRIGGER AS $$
DECLARE
today_max_queue INT;
BEGIN
SELECT COALESCE(MAX(nomor_antrean), 0)
INTO today_max_queue
FROM orders
WHERE DATE(created_at AT TIME ZONE 'Asia/Jakarta') = DATE(NOW() AT TIME ZONE 'Asia/Jakarta');

NEW.nomor_antrean := today_max_queue + 1;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_daily_queue_number
    BEFORE INSERT ON orders
    FOR EACH ROW
    EXECUTE FUNCTION generate_daily_queue_number();


-- B. Fungsi Otomatis Tambah Profile saat Pegawai Didaftarkan di Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
INSERT INTO public.profiles (id, username, role)
VALUES (
           NEW.id,
           COALESCE(NEW.raw_user_meta_data->>'username', NEW.email),
           'pegawai'
       );
RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();



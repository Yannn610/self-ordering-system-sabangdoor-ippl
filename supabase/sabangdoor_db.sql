CREATE POLICY "Pembeli: Buat Transaksi" ON orders FOR INSERT TO public WITH CHECK (true);
CREATE POLICY "Pembeli: Buat Detail Pesanan" ON order_items FOR INSERT TO public WITH CHECK (true);
CREATE POLICY "Pembeli: Lihat Nota Transaksi" ON orders FOR SELECT TO public USING (true);
CREATE POLICY "Pembeli: Lihat Item Nota" ON order_items FOR SELECT TO public USING (true);

-- Kebijakan Pegawai (Authenticated Users)
CREATE POLICY "Pegawai: Kelola Transaksi" ON orders FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Pegawai: Kelola Detail Transaksi" ON order_items FOR ALL TO authenticated USING (true);
CREATE POLICY "Pegawai: Kelola Menu" ON menus FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Pegawai: Lihat Profile" ON profiles FOR SELECT TO authenticated USING (true);


